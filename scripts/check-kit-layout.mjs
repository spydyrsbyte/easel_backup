export async function checkKitLayout(page) {
  await page.evaluate(async () => {
    const root = document.getElementById("root");
    root.replaceChildren();
    await kitRegistry.api.load("easel.maps.map@1");
    await kitRegistry.api.load("easel.layout.vttworkspace@1");
    const host = document.createElement("div");
    host.style.width = "480px";
    host.style.height = "260px";
    root.append(host);
    const manager = createKitComponents(kitRegistry, host);
    const map = manager.api.create("easel.maps.map@1", { props: { tokens: [{ id: "token-a", x: 96, y: 96, label: "Token A" }] } });
    manager.api.mountRoot(map);
    const wait = () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    const bounds = (node) => node.getBoundingClientRect();
    const check = (condition, message) => { if (!condition) throw new Error(message); };
    const fills = (node, parent, message) => {
      const a = bounds(node), b = bounds(parent);
      check(Math.abs(a.width - b.width) <= 2 && Math.abs(a.height - b.height) <= 2, message + `: ${a.width}x${a.height} in ${b.width}x${b.height}`);
    };
    await wait();
    fills(host.firstElementChild, host, "Standalone map must fill its parent");
    fills(host.querySelector(".kit-surface"), host, "Standalone map surface must fill its parent");
    host.style.width = "760px";
    host.style.height = "410px";
    await wait();
    fills(host.querySelector(".kit-surface"), host, "Map must resize with its parent");
    const selected = [];
    map.on("tokenSelect", (payload) => selected.push(payload));
    host.querySelector("[data-token-id='token-a']").click();
    check(selected[0]?.id === "token-a", "Map must emit token selection");
    const drops = [];
    map.on("dropRequest", (payload) => drops.push(payload));
    map.setProps({ camera: { x: 20, y: 30, zoom: 2, rotation: 90 } });
    const transfer = new DataTransfer();
    transfer.setData("application/x-easel-kit", JSON.stringify({ id: "actor-a", type: "character" }));
    const target = host.querySelector(".kit-surface");
    const rect = bounds(target);
    target.dispatchEvent(new DragEvent("drop", { clientX: rect.left + 120, clientY: rect.top + 110, dataTransfer: transfer, cancelable: true }));
    check(drops[0]?.data.id === "actor-a" && Math.abs(drops[0].position.x - 40) < 0.01 && Math.abs(drops[0].position.y + 50) < 0.01, "Object drops must report coordinates through the map camera transform");
    const workspace = manager.api.create("easel.layout.vttworkspace@1", { props: { sidebarWidth: 240 } });
    map.attach(workspace, "canvas");
    manager.api.mountRoot(workspace);
    await wait();
    fills(host.firstElementChild, host, "Workspace must use its parent height, not the browser height");
    const stage = host.querySelector(".kit-slot-canvas");
    const surface = host.querySelector(".kit-surface");
    fills(surface, stage, "Docked map must fill its canvas slot");
    check(Math.abs(bounds(stage).width - 520) <= 2, "Sidebar must reserve its configured width");
    workspace.setProps({ sidebarOpen: false });
    await wait();
    check(Math.abs(bounds(stage).width - 716) <= 2, "Collapsed sidebar must release canvas space");
    host.style.width = "280px";
    host.style.height = "180px";
    workspace.setProps({ sidebarOpen: true, sidebarWidth: 340 });
    await wait();
    check(bounds(stage).width >= 158, "Small containers must retain usable map space");
    fills(surface, stage, "Map must fill a small canvas slot");
    await new Promise((resolve) => setTimeout(resolve, 100));
    const canvas = host.querySelector("canvas");
    check(Boolean(canvas), "Map must mount its Pixi canvas");
    const ratio = devicePixelRatio || 1;
    check(Math.abs(canvas.width / ratio - surface.clientWidth) <= 2 && Math.abs(canvas.height / ratio - surface.clientHeight) <= 2, "Pixi renderer must resize with the actual surface");
    manager.destroy();
    root.replaceChildren();
    await kitRegistry.api.load("easel.collections.compendium@1");
    const library = createKitComponents(kitRegistry, root);
    const entries = Array.from({ length: 2500 }, (_, index) => ({ id: String(index), name: "Entry " + index, level: 1 }));
    const compendium = library.api.create("easel.collections.compendium@1", { props: { entries } });
    library.api.mountRoot(compendium);
    check(root.querySelectorAll(".kit-compendium-row").length < 30, "Compendium must virtualize large packs");
    const viewport = root.querySelector(".kit-compendium-viewport");
    viewport.scrollTop = 30000;
    viewport.dispatchEvent(new Event("scroll"));
    const search = root.querySelector(".kit-compendium-bar input[type='search']");
    search.value = "Entry 2499";
    search.dispatchEvent(new Event("input"));
    check(root.querySelectorAll(".kit-compendium-row").length === 1, "Filtering a scrolled compendium must reveal matching rows");
    search.value = "";
    search.dispatchEvent(new Event("input"));
    check(root.querySelectorAll(".kit-compendium-row").length > 1, "Clearing compendium search must restore entries");
    library.destroy();
    root.replaceChildren();
  });
}
